import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE ERROR:', m.text()); });
page.on('pageerror', e => console.log('PAGE ERROR:', e.message));
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
const card = page.locator('[data-testid^="project-card-"]').first();
await card.click();
await page.waitForTimeout(1200);
await page.screenshot({ path: '/tmp/shot-project.png' });
const row = page.locator('[data-testid^="hook-row-"]').first();
await row.click();
await page.waitForTimeout(1200);
await page.screenshot({ path: '/tmp/shot-hook.png' });
await page.locator('[data-testid="tab-timeline"]').click();
await page.waitForTimeout(900);
await page.screenshot({ path: '/tmp/shot-timeline.png' });
await page.locator('[data-testid="tab-deliveries"]').click();
await page.waitForTimeout(900);
await page.screenshot({ path: '/tmp/shot-deliveries.png' });
await browser.close();
console.log('done');
